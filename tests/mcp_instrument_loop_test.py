"""Exercise the existing MCP instrument loop against real rendered musical output."""
import argparse
import asyncio
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile
import uuid

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client
from mcp_control_test import fixture_command

ROOT = Path(__file__).resolve().parents[1]


async def exercise(fixture: str, output: Path) -> None:
    """Render an authored C-major phrase before/after MCP edits and verify exact history restoration."""
    with tempfile.TemporaryDirectory(prefix="daw-loop-", dir="/tmp") as directory:
        endpoint = str(Path(directory) / "control.sock")
        process = subprocess.Popen([fixture, endpoint, "write", str(output)], stdin=subprocess.PIPE,
                                   stdout=subprocess.PIPE, text=True, bufsize=1)
        results = {}
        try:
            assert process.stdout.readline().strip() == "READY"
            fixture_command(process, "phrase")
            parameters = StdioServerParameters(command=str(ROOT / "tools/mcp/run.sh"),
                                               env=dict(os.environ, DAW_CONTROL_SOCKET=endpoint))
            async with stdio_client(parameters) as (read, write):
                async with ClientSession(read, write) as session:
                    initialized = await session.initialize()

                    async def call(name: str, **args) -> dict:
                        """Require both protocol and domain acceptance for each creative action."""
                        result = await session.call_tool(name, args)
                        assert not result.isError, result
                        value = result.structuredContent or json.loads(result.content[0].text)
                        assert value["ok"], value
                        return value

                    cap = await call("capabilities")
                    project = await call("inspect_project")
                    item = next(t for t in project["targets"] if t["kind"] == "midi_region")
                    target = {key: value for key, value in item.items() if key != "name"}
                    state = await call("get_instrument", target=target)
                    assert state["instrument"]["inherits_track"]

                    def render(label: str, expected_notes: int = 8) -> dict:
                        """Measure and hash files generated by the engine on its owner thread."""
                        measured = json.loads(fixture_command(process, "render " + label).removeprefix("DONE "))
                        measured["sha256"] = hashlib.sha256((output / f"{label}.wav").read_bytes()).hexdigest()
                        assert measured["notes"] == expected_notes and measured["frames"] == 120000
                        assert 0 < measured["rms"] < measured["peak"] < .95, measured
                        results[label] = measured
                        return measured

                    baseline = render("baseline")
                    edit_id = str(uuid.uuid4())
                    edited = await call("set_instrument", instance=cap["instance"], request_id=edit_id,
                        target=target, expected_state=state["expected_state"], preset="pluck",
                        parameters={"attack_ms": 1.8, "decay_ms": 180, "sustain": .2, "release_ms": 80,
                                    "tone": .65, "drive": .15, "osc_mix": .35, "level": .75})
                    pluck = render("edited")
                    assert pluck["sha256"] != baseline["sha256"]
                    assert await call("request_status", instance=cap["instance"], request_id=edit_id) == edited
                    undo = await call("undo_instrument", instance=cap["instance"], request_id=str(uuid.uuid4()),
                                      target=target, expected_state=edited["expected_state"])
                    assert undo["instrument"]["inherits_track"]
                    assert render("undo")["sha256"] == baseline["sha256"]
                    redo = await call("redo_instrument", instance=cap["instance"], request_id=str(uuid.uuid4()),
                                      target=target, expected_state=undo["expected_state"])
                    assert render("redo")["sha256"] == pluck["sha256"]
                    motion = await call("set_instrument", instance=cap["instance"], request_id=str(uuid.uuid4()),
                        target=target, expected_state=redo["expected_state"], preset="synth_lab",
                        parameters={"level": .55, "tone": .5, "osc_mix": .38, "osc2_detune": 7,
                                    "sub_mix": .12, "drive": .1, "attack_ms": 8, "decay_ms": 160,
                                    "sustain": .55, "release_ms": 65, "vibrato_rate": 4.5, "vibrato_depth": 4})
                    assert render("motion")["sha256"] not in (pluck["sha256"], baseline["sha256"])
                    readback = await call("get_instrument", target=target)
                    assert readback["expected_state"] == motion["expected_state"]
                    rounded = {}
                    for name in ("rounded_keys", "rounded_pluck", "rounded_pad", "filtered_keys", "filtered_pad", "sweep_bass", "filter_pluck", "moving_pad"):
                        selected = await call("set_instrument", instance=cap["instance"], request_id=str(uuid.uuid4()),
                            target=target, expected_state=readback["expected_state"], preset=name, parameters={})
                        defaults = next(p["defaults"] for p in cap["presets"] if p["id"] == name)
                        actual = selected["instrument"]
                        assert actual["effective_preset"] == name, actual
                        assert actual["effective_parameters"] == defaults, actual
                        rounded[name] = render(name)
                        restored = await call("undo_instrument", instance=cap["instance"], request_id=str(uuid.uuid4()),
                            target=target, expected_state=selected["expected_state"])
                        assert restored["instrument"] == readback["instrument"]
                        selected = await call("redo_instrument", instance=cap["instance"], request_id=str(uuid.uuid4()),
                            target=target, expected_state=restored["expected_state"])
                        assert render(name)["sha256"] == rounded[name]["sha256"]
                        readback = await call("get_instrument", target=target)
                    assert len({v["sha256"] for v in rounded.values()}) == 8
                    original_motion = render("moving_pad")
                    modulated = await call("set_instrument", instance=cap["instance"], request_id=str(uuid.uuid4()), target=target,
                        expected_state=readback["expected_state"], parameters={"filter_env_octaves":2.4,"filter_decay_ms":180,"filter_lfo_hz":2,"filter_lfo_octaves":1.2})
                    changed_motion = render("mod_edit")
                    assert changed_motion["sha256"] != original_motion["sha256"]
                    unmodulated = await call("undo_instrument", instance=cap["instance"], request_id=str(uuid.uuid4()), target=target, expected_state=modulated["expected_state"])
                    assert render("mod_undo")["sha256"] == original_motion["sha256"]
                    readback = await call("redo_instrument", instance=cap["instance"], request_id=str(uuid.uuid4()), target=target, expected_state=unmodulated["expected_state"])
                    assert render("mod_redo")["sha256"] == changed_motion["sha256"]
                    fixture_command(process, "chord")
                    render("filtered_pad_chord", expected_notes=4)
                    report = {"protocol": initialized.protocolVersion, "results": results,
                              "capabilities": cap, "final_instrument": readback,
                              "scope": "isolated authored C-major phrase; no effects, normalization, user project or physical listening"}
                    (output / "instrument-loop.json").write_text(json.dumps(report, indent=2) + "\n")
        finally:
            process.terminate()
            try:
                process.wait(timeout=10)
            except subprocess.TimeoutExpired:
                process.kill(); process.wait(timeout=5)
                raise
            assert process.returncode == 0
    print(f"mcp_instrument_loop_test: success; exact undo/redo WAV restoration; {output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--fixture", required=True)
    parser.add_argument("--output-root", required=True)
    args = parser.parse_args()
    output_root = Path(args.output_root).resolve()
    output_root.mkdir(parents=True, exist_ok=True)
    output = Path(tempfile.mkdtemp(prefix="instrument-loop-", dir=output_root))
    asyncio.run(exercise(str(Path(args.fixture).resolve()), output))
